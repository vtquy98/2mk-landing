// Webflow -> Astro import. Run after crawl.mjs:
//   node scripts/webflow-import/run.mjs [collection…]   (no argument = everything)
// Writes: src/content/<collection>/*.md, src/data/**.json, public/_redirects, public/assets/* (downloaded).
// Content written here is the starting point; once Webflow is off, edit the files in src/ directly and delete this folder.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { assetEntries, CACHE, extractSeo, loadPage, ROOT, rewriteUrls, saveAssetMap, statuses, writeData, isSiteGraph } from './lib.mjs';

const only = process.argv.slice(2);

// 1. Redirects (Webflow 301 rules) -> Cloudflare static assets _redirects
const redirects = statuses().filter(s => s[1] === 301).map(([from, , to]) => `${from} ${to.replace(/^https?:\/\/(www\.)?2ndmarket\.fr(?=\/)/, '')} 301`);
writeFileSync(join(ROOT, 'public/_redirects'), `# Webflow 301 rules, generated by scripts/webflow-import/run.mjs\n${redirects.join('\n')}\n`);

// 2. Site-wide JSON-LD (Organization/WebSite graph, identical on every page) and SEO of every static page
{
  const $ = loadPage('/');
  const graph = $('script[type="application/ld+json"]').toArray().map(s => $(s).html().trim()).find(isSiteGraph);
  writeData('site-jsonld.json', JSON.parse(rewriteUrls(graph)));
  const statics = statuses().filter(s => s[1] === 200 && !s[0].slice(1).includes('/')).map(s => s[0]).concat('/404');
  for (const p of statics) writeData(`seo/${p === '/' ? 'index' : p.slice(1)}.json`, extractSeo(loadPage(p)));
}

// 2b. Every Webflow CDN file referenced anywhere (pages + Webflow CSS) is self-hosted: Webflow will be switched off.
for (const f of readdirSync(join(CACHE, 'pages'), { recursive: true }).map(String).filter(f => f.endsWith('.html')).concat('../webflow.css'))
  rewriteUrls(readFileSync(join(CACHE, 'pages', f), 'utf8'));

// 3. Collections: every module in ./collections exports `default async function()`.
const dir = join(import.meta.dirname, 'collections');
for (const f of existsSync(dir) ? readdirSync(dir).filter(f => f.endsWith('.mjs')) : []) {
  if (only.length && !only.includes(f.replace('.mjs', ''))) continue;
  const n = await (await import(join(dir, f))).default();
  console.log(`${f}: ${n ?? '?'} entries`);
}
saveAssetMap();

// 4. Download every referenced Webflow asset that isn't in public/assets yet
const out = join(ROOT, 'public');
mkdirSync(join(out, 'assets'), { recursive: true });
const todo = assetEntries().filter(([, local]) => !existsSync(join(out, local)));
const failed = [];
const q = [...todo];
await Promise.all(Array.from({ length: 8 }, async () => {
  while (q.length) {
    const [url, local] = q.shift();
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error(r.status);
      writeFileSync(join(out, local), Buffer.from(await r.arrayBuffer()));
    } catch (e) { failed.push(`${url} ${e.message}`); }
  }
}));
console.log(`redirects: ${redirects.length}, assets: ${assetEntries().length} known, ${todo.length - failed.length} downloaded`);
if (failed.length) { console.error(`asset download failed:\n${failed.join('\n')}`); process.exitCode = 1; }
